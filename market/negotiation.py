"""Multi-round negotiation protocol (Team B3).

``GridModel`` collects one order list per agent for every round and calls
:meth:`NegotiationProtocol.refine` before clearing. Agents own their own
counter-offer rule in ``decide(round)`` (consumers use ``raise_factor`` capped
by their ceiling, producers use ``producer_step`` floored at marginal cost).
The protocol validates and orders the resulting counter-offers so the market
never clears a malformed round.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any, Mapping, Sequence

from market.auction import ClearingResult, MarketContext
from market.orders import Order


class NegotiationProtocol(ABC):
    """Contract for the multi-round negotiation behaviour."""

    @property
    @abstractmethod
    def rounds(self) -> int:
        """Maximum number of rounds, configured in ``simulation.rounds``."""

    @abstractmethod
    def refine(
        self,
        round: int,
        orders: Sequence[Order],
        previous: ClearingResult | None,
        context: MarketContext,
    ) -> list[Order]:
        """Adjust the orders of a negotiation round before clearing."""


class RaiseFactorNegotiation(NegotiationProtocol):
    """Validating negotiation protocol for the official auction.

    Counter offers are generated by the agents' round-aware ``decide`` method,
    which keeps buyer ceilings and producer marginal-cost floors private to the
    owning agent. This protocol enforces that every counter offer belongs to
    the current round and that buy prices respect the published ceilings.
    """

    def __init__(self, config: Mapping[str, Any]) -> None:
        """Create the protocol.

        Args:
            config: Full validated configuration.
        """

        self._rounds = int(config["simulation"]["rounds"])
        self._raise_factor = float(config["market"]["raise_factor"])
        self._producer_step = float(config["market"]["producer_step"])

    @property
    def rounds(self) -> int:
        """Maximum number of negotiation rounds."""

        return self._rounds

    @property
    def raise_factor(self) -> float:
        """Consumer counter-offer escalation factor."""

        return self._raise_factor

    @property
    def producer_step(self) -> float:
        """Producer counter-offer reduction per round."""

        return self._producer_step

    def refine(
        self,
        round: int,
        orders: Sequence[Order],
        previous: ClearingResult | None,
        context: MarketContext,
    ) -> list[Order]:
        """Validate one round of counter offers.

        Args:
            round: Current round, starting at ``2``.
            orders: Orders produced by the agents for this round.
            previous: Clearing result of the previous round, if any.
            context: Current market context.

        Returns:
            The orders to clear in this round, in deterministic agent order.

        Raises:
            ValueError: If an order carries the wrong round or violates a
                published consumer ceiling.
        """

        del previous  # The protocol is stateless; agents keep their own history.
        refined: list[Order] = []
        for order in orders:
            if order.round != round:
                raise ValueError(
                    f"order for {order.agent_id} carries round {order.round} "
                    f"instead of {round}"
                )
            if order.side == "buy":
                ceiling = context.max_price.get(order.agent_id)
                if ceiling is not None and order.price > float(ceiling) + 1e-9:
                    raise ValueError(
                        f"buy order for {order.agent_id} exceeds the ceiling {ceiling}"
                    )
            refined.append(order)
        refined.sort(key=lambda order: (order.side, order.agent_id, order.priority))
        return refined


class StubNegotiation(NegotiationProtocol):
    """Identity protocol retained for the frozen mock-mode constructor.

    It is not used by any official experiment and never produces results on its
    own; it simply passes validated orders through.
    """

    def __init__(self, rounds: int) -> None:
        """Store the configured number of rounds."""

        self._rounds = int(rounds)

    @property
    def rounds(self) -> int:
        """Maximum number of negotiation rounds."""

        return self._rounds

    def refine(
        self,
        round: int,
        orders: Sequence[Order],
        previous: ClearingResult | None,
        context: MarketContext,
    ) -> list[Order]:
        """Return the orders unchanged."""

        del previous, context
        return [order for order in orders if order.round == round]


__all__ = ["NegotiationProtocol", "RaiseFactorNegotiation", "StubNegotiation"]
